"""Build Flipper/Data/RecipeDB.lua from the wowapi static cache (Forever namespace).

Maps every recipe *item* (Recipe:/Pattern:/Formula:/Plans:/Schematic:/Manual:) to the
craft it teaches: profession, required skill, output item, quantity range and reagents.
The in-game client can't read unlearned recipes, so this ships with the addon.

Usage: python tools/build_recipe_db.py [path/to/wowapi-static.sqlite]
Refresh the cache first with wowapi's warm_cache / auction-data/fetch_recipes.py.
"""
import json
import pathlib
import sqlite3
import sys
import zlib

NS = "static-forever-us"
DEFAULT_DB = pathlib.Path(r"C:\Users\igots\Documents\wow-tools\wowapi\.cache\wowapi-static.sqlite")
OUT = pathlib.Path(__file__).resolve().parent.parent / "Flipper" / "Data" / "RecipeDB.lua"
CRAFTING = {"Alchemy", "Blacksmithing", "Cooking", "Enchanting", "Engineering", "First Aid",
            "Leatherworking", "Tailoring"}


def main():
    db = sqlite3.connect(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DB)

    def rows(prefix):
        for path, body in db.execute(
                "select path, body from responses where ns=? and status=200 and path like ?", (NS, prefix + "%")):
            try:
                body = zlib.decompress(body)
            except zlib.error:
                pass
            yield path, json.loads(body)

    # recipe id -> profession name, from each profession's skill tier
    profession_of = {}
    for path, tier in rows("/data/wow/profession/"):
        if "/skill-tier/" not in path:
            continue
        prof = tier.get("name")
        for cat in tier.get("categories", []):
            for r in cat.get("recipes", []):
                profession_of[r["id"]] = prof

    # (profession, recipe name) -> craft
    crafts = {}
    for _, r in rows("/data/wow/recipe/"):
        prof = profession_of.get(r.get("id"))
        out = r.get("crafted_item") or r.get("alliance_crafted_item")
        if prof not in CRAFTING or not out or not r.get("reagents"):
            continue
        q = r.get("crafted_quantity") or {}
        qmin = int(q.get("value") or q.get("minimum") or 1)
        qmax = int(q.get("value") or q.get("maximum") or qmin)
        crafts[(prof, r["name"].lower())] = {
            "output": out["id"], "qmin": qmin, "qmax": qmax,
            "reagents": [(x["reagent"]["id"], x["quantity"]) for x in r["reagents"]],
            "name": r["name"],
        }

    entries, unmatched = {}, 0
    for _, item in rows("/data/wow/item/"):
        if (item.get("item_class") or {}).get("id") != 9:
            continue
        name = item.get("name", "")
        if ": " not in name:
            continue
        prof = (item.get("item_subclass") or {}).get("name")
        craft = crafts.get((prof, name.split(": ", 1)[1].lower()))
        if not craft:
            unmatched += 1
            continue
        skill = (((item.get("preview_item") or {}).get("requirements") or {}).get("skill") or {}).get("level", 0)
        entries[item["id"]] = dict(craft, profession=prof, skill=skill)

    build = db.execute("select body from responses where ns=? and path like '/data/wow/recipe/%' limit 1", (NS,)).fetchone()
    try:
        build = zlib.decompress(build[0])
    except zlib.error:
        build = build[0]
    build = json.loads(build)["_links"]["self"]["href"].split("namespace=")[-1]
    lines = [f"-- Generated by tools/build_recipe_db.py from Blizzard's Forever game data ({build}). Do not edit.",
             "-- [recipeItemID] = {profession, requiredSkill, recipeName, outputItemID, qtyMin, qtyMax, {reagentID, qty, ...}}",
             "local _, ns = ...", f'ns.RecipeDBBuild = "{build}"', "ns.RecipeDB = {"]
    for item_id in sorted(entries):
        e = entries[item_id]
        flat = ", ".join(f"{rid}, {qty}" for rid, qty in e["reagents"])
        lines.append(f'  [{item_id}] = {{"{e["profession"]}", {e["skill"]}, {json.dumps(e["name"])}, '
                     f'{e["output"]}, {e["qmin"]}, {e["qmax"]}, {{{flat}}}}},')
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(entries)} recipe items written to {OUT} ({unmatched} recipe items without a matching craft)")


if __name__ == "__main__":
    main()
