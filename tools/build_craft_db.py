"""Build Flipper/Data/CraftDB.lua from the wowapi static cache (Forever namespace).

Every profession recipe Blizzard's Forever data lists - trainer-taught ones and enchants
included - with its reagents, for the "Used in" tooltip lines. Skill levels are only known
for recipes taught by an item (the item says so); the API has none for trainer recipes, so
those are written as 0.

Usage: python tools/build_craft_db.py [path/to/wowapi-static.sqlite]
"""
import json
import pathlib
import sqlite3
import sys
import zlib

NS = "static-forever-us"
DEFAULT_DB = pathlib.Path(r"C:\Users\igots\Documents\wow-tools\wowapi\.cache\wowapi-static.sqlite")
OUT = pathlib.Path(__file__).resolve().parent.parent / "Flipper" / "Data" / "CraftDB.lua"


def main():
    db = sqlite3.connect(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DB)

    def rows(prefix):
        for path, body in db.execute(
                "select path, body from responses where ns=? and status=200 and path like ?", (NS, prefix + "%")):
            try:
                body = zlib.decompress(body)
            except zlib.error:
                pass
            yield path, json.loads(body)

    profession_of = {}
    for path, tier in rows("/data/wow/profession/"):
        if "/skill-tier/" not in path:
            continue
        for cat in tier.get("categories", []):
            for r in cat.get("recipes", []):
                profession_of[r["id"]] = tier.get("name")

    # Skill needed, from the item that teaches the recipe (when there is one).
    skill_of = {}
    for _, item in rows("/data/wow/item/"):
        name = item.get("name", "")
        if (item.get("item_class") or {}).get("id") != 9 or ": " not in name or name.startswith("Blueprint:"):
            continue
        prof = (item.get("item_subclass") or {}).get("name")
        skill = (((item.get("preview_item") or {}).get("requirements") or {}).get("skill") or {}).get("level", 0)
        skill_of[(prof, name.split(": ", 1)[1].lower())] = skill

    entries, build = [], None
    for _, r in rows("/data/wow/recipe/"):
        prof = profession_of.get(r.get("id"))
        if not prof or not r.get("reagents") or not r.get("name"):
            continue
        build = build or r["_links"]["self"]["href"].split("namespace=")[-1]
        out = r.get("crafted_item") or r.get("alliance_crafted_item") or {}
        entries.append((prof, r["name"], skill_of.get((prof, r["name"].lower()), 0), out.get("id", 0),
                        [(x["reagent"]["id"], x["quantity"]) for x in r["reagents"]]))
    entries.sort()

    lines = [f"-- Generated by tools/build_craft_db.py from Blizzard's Forever game data ({build}). Do not edit.",
             "-- {profession, recipeName, requiredSkill (0 = not known: trainer recipes), outputItemID (0 = none), {reagentID, qty, ...}}",
             "local _, ns = ...", "ns.CraftDB = {"]
    for prof, name, skill, out, reagents in entries:
        flat = ", ".join(f"{rid}, {qty}" for rid, qty in reagents)
        lines.append(f'  {{"{prof}", {json.dumps(name)}, {skill}, {out}, {{{flat}}}}},')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    by_prof = {}
    for e in entries:
        by_prof[e[0]] = by_prof.get(e[0], 0) + 1
    print(f"{len(entries)} recipes written to {OUT}")
    print(", ".join(f"{k} {v}" for k, v in sorted(by_prof.items())))
    print(f"{sum(1 for e in entries if e[2])} with a skill level, {sum(1 for e in entries if not e[3])} without an output item")


if __name__ == "__main__":
    main()
