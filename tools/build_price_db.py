"""Build Flipper/Data/BuyPriceDB.lua: what a vendor charges for each item (Blizzard's Forever
item data, purchase_price / purchase_quantity). Whether a vendor actually sells the item is
decided in game (QuestieDB vendor lists, or merchants you have opened), not here.

Usage: python tools/build_price_db.py [path/to/wowapi-static.sqlite]
"""
import json
import pathlib
import sqlite3
import sys
import zlib

NS = "static-forever-us"
DEFAULT_DB = pathlib.Path(r"C:\Users\igots\Documents\wow-tools\wowapi\.cache\wowapi-static.sqlite")
OUT = pathlib.Path(__file__).resolve().parent.parent / "Flipper" / "Data" / "BuyPriceDB.lua"


def main():
    db = sqlite3.connect(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DB)
    prices, build = {}, None
    for (body,) in db.execute(
            "select body from responses where ns=? and status=200 and path like '/data/wow/item/%'", (NS,)):
        try:
            body = zlib.decompress(body)
        except zlib.error:
            pass
        item = json.loads(body)
        build = build or item["_links"]["self"]["href"].split("namespace=")[-1]
        price = item.get("purchase_price") or 0
        if price > 0:
            prices[item["id"]] = (price, item.get("purchase_quantity") or 1)
    lines = [f"-- Generated by tools/build_price_db.py from Blizzard's Forever item data ({build}). Do not edit.",
             "-- [itemID] = vendor price for one purchase, or {price, quantity} when a purchase gives a stack.",
             "local _, ns = ...", "ns.BuyPriceDB = {"]
    for item_id in sorted(prices):
        price, qty = prices[item_id]
        lines.append(f"  [{item_id}] = {price}," if qty == 1 else f"  [{item_id}] = {{{price}, {qty}}},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(prices)} buy prices written to {OUT}")


if __name__ == "__main__":
    main()
